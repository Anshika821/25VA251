function showStringMethods()
{
    let name = "Anshika";

    let upperCase = name.toUpperCase();
    let lowerCase = name.toLowerCase();
    let length = name.length;

    alert(
        "Original: " + name +
        "\nUpper Case: " + upperCase +
        "\nLower Case: " + lowerCase +
        "\nLength: " + length
    );
}